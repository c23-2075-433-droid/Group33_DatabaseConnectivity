using System;
using System.Collections.Generic;
using System.Globalization;

/// <summary>
/// The pronunciation classifier for the six strictly judged words
/// (AmbiguousWords: Tayo, Upo, Bukas, Basa, Bati, Pasok), learned from the
/// group's own recorded dataset: several speakers, each saying every word
/// the taught way three times and the other way three times
/// (Tools/pronunciation_dataset). It answers one question: was the word said
/// the taught way (tayô, "stand up") or the other way (táyo, "we")?
///
/// WHAT IT LOOKS AT, AND WHAT IT NEVER LOOKS AT
///
/// Every feature compares one part of the child's word with another part of
/// the SAME word, so a high or low voice, a loud or quiet one, a child or an
/// adult, a near or far phone, and a slow or fast speaker all cancel out:
///
///   length    log ratio of the first vowel's length to the second's. Tagalog
///             stress is mostly vowel LENGTH: bá-sa has a long a, ba-sâ a short one.
///   pitch     semitones between the two vowels' median pitch, each measured
///             against the speaker's own voice.
///   loudness  dB between the two vowels.
///   fall      semitones the pitch falls inside the last vowel (a stressed
///             final vowel cut by a glottal stop falls differently).
///   template  the whole word lined up (dynamic time warping) with every
///             recorded speaker's taught and other pronunciation, compared on
///             speaker-normalised pitch, loudness and timing
///             (PronunciationTemplate.Distance): nearest other minus nearest taught.
///
/// The child's absolute pitch, loudness and speed are never features, and no
/// feature asks "does this sound like the recorded speakers' voices".
///
/// HOW IT DECIDES
///
/// One small logistic regression per word turns the features (standardised)
/// into p = the probability the word was said the taught way. Each answer is
/// measured six ways (three frame offsets, with and without a little noise),
/// and at least four of the six must find the word's syllables:
///
///   Correct     the median p is at least acceptFrom, and no measurement
///               is below 0.4 (MinLowForCorrect)
///   Incorrect   the median p is at most rejectFrom, and no measurement is
///               at or above acceptFrom
///   Uncertain   anything else, or fewer than four measurements (noise, a
///               cut-off word, another word around it).
///
/// (Until 2026-11-22 all six had to succeed and all six had to clear the
/// line. Tried on a real speaker saying the words naturally, that asked
/// again on most correct answers: one stray measurement was enough.)
///
/// The weights, lines and reference frames are generated by
/// PronunciationModelBuilder into PronunciationModelData.cs, so the game
/// needs no audio files and no network at run time. Plain C#: the same code
/// runs on the phone, in the Editor and in Tools/stresstests.
/// </summary>
public static partial class PronunciationModel
{
    public enum Verdict { Correct, Incorrect, Uncertain }

    public struct Result
    {
        public Verdict verdict;
        /// <summary>Lowest, median and highest probability of the taught pronunciation over the measurements (NaN if none).</summary>
        public float pLow, pMid, pHigh;
        public int measurements, measured;
        /// <summary>The features of the first successful measurement, for the attempt log.</summary>
        public float[] features;
        public string reason;
    }

    public const int FeatureCount = 5;
    public static readonly string[] FeatureNames = { "length", "pitch", "loudness", "fall", "template" };
    public const int Length = 0, Pitch = 1, Loudness = 2, Fall = 3, Template = 4;

    /// <summary>One word's trained classifier.</summary>
    public sealed class Model
    {
        public string word;
        public bool[] use = new bool[FeatureCount];
        public float[] mean = new float[FeatureCount], scale = new float[FeatureCount], weight = new float[FeatureCount];
        public float bias;
        public float acceptFrom = 0.8f, rejectFrom = 0.2f;
        /// <summary>Recorded taught and other pronunciations, for the template feature.</summary>
        public List<PronunciationTemplate.Frames> taughtRefs = new List<PronunciationTemplate.Frames>();
        public List<PronunciationTemplate.Frames> otherRefs = new List<PronunciationTemplate.Frames>();
        /// <summary>Where the model came from, e.g. "3 speakers (gar, la, olyk), 108 takes".</summary>
        public string trainedOn = "";
    }

    // ---- Features ---------------------------------------------------------------

    /// <summary>
    /// The features of one recording of the word, or null (with why) when the
    /// word's syllables cannot be found in it. A feature that cannot be
    /// measured (no voiced frames in a vowel) is NaN and counts as neutral.
    /// </summary>
    public static float[] Measure(SpeechFeatures s, StressPattern pattern, Model model, out string whyNot)
    {
        whyNot = null;
        if (pattern == null || pattern.SyllableCount != 2) { whyNot = "the classifier handles two-syllable words only"; return null; }
        SyllableAligner.Alignment a = SyllableAligner.Align(s, pattern.Word);
        string problem = PronunciationAssessor.Problem(a, pattern);
        if (problem != null) { whyNot = problem; return null; }

        SyllableAligner.Syllable v1 = a.syllables[0], v2 = a.syllables[1];
        float[] f = new float[FeatureCount];
        f[Length] = (float)Math.Log((v1.lengthMs + 10f) / (v2.lengthMs + 10f));
        f[Pitch] = v1.pitchHz > 0 && v2.pitchHz > 0
            ? Clamp((float)(12 * Math.Log(v1.pitchHz / v2.pitchHz, 2)), -15f, 15f)
            : float.NaN;
        f[Loudness] = Clamp(v1.loudDb - v2.loudDb, -25f, 25f);
        f[Fall] = FallWithin(s, v2, a.medianPitchHz);
        f[Template] = float.NaN;
        if (model != null && model.use[Template] && model.taughtRefs.Count > 0 && model.otherRefs.Count > 0)
            f[Template] = TemplateScore(s, model.taughtRefs, model.otherRefs);
        return f;
    }

    /// <summary>Nearest other pronunciation minus nearest taught one (positive = taught), NaN if the word cannot be lined up.</summary>
    public static float TemplateScore(SpeechFeatures s, IList<PronunciationTemplate.Frames> taught, IList<PronunciationTemplate.Frames> other)
    {
        string why;
        PronunciationTemplate.Frames fr = PronunciationTemplate.Extract(s, out why);
        if (fr == null) return float.NaN;
        float score = PronunciationTemplate.Score(fr, taught, other);
        return float.IsNaN(score) || float.IsInfinity(score) ? float.NaN : Clamp(score, -10f, 10f);
    }

    /// <summary>Semitones from the first third of a vowel to its last third (positive = falling).</summary>
    private static float FallWithin(SpeechFeatures s, SyllableAligner.Syllable v, float medianHz)
    {
        int n = v.to - v.from + 1;
        if (n < 6 || medianHz <= 0) return float.NaN;
        List<float> head = new List<float>(), tail = new List<float>();
        for (int f = v.from; f <= v.to; f++)
        {
            if (f < 0 || f >= s.Count || s.f0[f] <= 0 || s.periodicity[f] <= 0.6f) continue;
            float hz = s.f0[f];
            while (hz > medianHz * 1.8f) hz *= 0.5f;
            while (hz < medianHz / 1.8f) hz *= 2f;
            if (f < v.from + n / 3) head.Add(hz);
            else if (f > v.to - n / 3) tail.Add(hz);
        }
        if (head.Count < 2 || tail.Count < 2) return float.NaN;
        float h = SpeechFeatures.Percentile(head, 0.5f), t = SpeechFeatures.Percentile(tail, 0.5f);
        return Clamp((float)(12 * Math.Log(h / t, 2)), -12f, 12f);
    }

    /// <summary>The probability that features f are the taught pronunciation.</summary>
    public static float Probability(Model m, float[] f)
    {
        double z = m.bias;
        for (int i = 0; i < FeatureCount; i++)
        {
            if (!m.use[i]) continue;
            z += m.weight[i] * Standardise(m, i, f[i]);
        }
        return (float)(1.0 / (1.0 + Math.Exp(-z)));
    }

    /// <summary>A feature in units of the training data's spread, NaN as neutral, clamped so one wild value cannot decide alone.</summary>
    public static float Standardise(Model m, int i, float v)
    {
        if (float.IsNaN(v)) return 0f;
        return Clamp((v - m.mean[i]) / m.scale[i], -4f, 4f);
    }

    // ---- Judging an answer ----------------------------------------------------------

    private static readonly int[] Offsets = { 0, 48, 96 };

    public static Result Assess(float[] samples, int sampleRate, string word)
    {
        return Assess(samples, sampleRate, StressPattern.For(word), For(word));
    }

    public static Result Assess(float[] samples, int sampleRate, StressPattern pattern, Model model)
    {
        Result r = new Result { verdict = Verdict.Uncertain, pLow = float.NaN, pMid = float.NaN, pHigh = float.NaN };
        if (model == null) { r.reason = "no trained model for this word"; return r; }
        if (samples == null || sampleRate <= 0 || samples.Length < sampleRate / 5) { r.reason = "no audio was recorded"; return r; }

        float[] x16 = SpeechFeatures.Resample(samples, sampleRate, SpeechFeatures.SampleRate);
        float low = float.MaxValue, high = float.MinValue;
        List<float> ps = new List<float>();
        string problem = null;
        for (int pass = 0; pass < Offsets.Length * 2; pass++)
        {
            r.measurements++;
            float[] x = pass >= Offsets.Length ? WithNoise(x16, -58f, 3000 + pass) : x16;
            string why;
            float[] f = Measure(SpeechFeatures.Of(x, SpeechFeatures.SampleRate, Offsets[pass % Offsets.Length]), pattern, model, out why);
            if (f == null) { if (problem == null) problem = why; continue; }
            if (r.features == null) r.features = f;
            float p = Probability(model, f);
            ps.Add(p);
            r.measured++;
            low = Math.Min(low, p);
            high = Math.Max(high, p);
        }
        if (r.measured == 0) { r.reason = problem ?? "could not measure the word"; return r; }
        r.pLow = low;
        r.pHigh = high;
        r.pMid = SpeechFeatures.Percentile(ps, 0.5f);

        CultureInfo inv = CultureInfo.InvariantCulture;
        string where = " (p " + r.pMid.ToString("0.00", inv) + ", range " + low.ToString("0.00", inv) + ".." + high.ToString("0.00", inv) +
                       ", " + r.measured + "/" + r.measurements + " measured; correct from " + model.acceptFrom.ToString("0.00", inv) +
                       ", incorrect below " + model.rejectFrom.ToString("0.00", inv) + ")";
        r.verdict = Decide(low, r.pMid, high, r.measured, model.acceptFrom, model.rejectFrom);
        if (r.measured < MinMeasured) r.reason = "the word could not be heard clearly enough" + where;
        else if (r.verdict == Verdict.Correct) r.reason = "said the taught way" + where;
        else if (r.verdict == Verdict.Incorrect) r.reason = "said the other way" + where;
        else r.reason = "not clearly either pronunciation" + where;
        return r;
    }

    /// <summary>How many of the six measurements must find the word for a verdict.</summary>
    public const int MinMeasured = 4;

    /// <summary>
    /// For Correct, no single measurement may fall below this: an answer whose
    /// measurements reach down toward the other pronunciation is asked again.
    /// Added 2026-11-22 after a simulated child-like, slow úpo was accepted with
    /// measurements from 0.32 to 0.81; on real takes it cost 2 of 108 acceptances.
    /// </summary>
    public const float MinLowForCorrect = 0.4f;

    /// <summary>The verdict from the measurements' probabilities (see the class summary).</summary>
    public static Verdict Decide(float low, float mid, float high, int measured, float acceptFrom, float rejectFrom)
    {
        if (measured < MinMeasured || float.IsNaN(mid)) return Verdict.Uncertain;
        if (mid >= acceptFrom && low >= Math.Max(rejectFrom, MinLowForCorrect)) return Verdict.Correct;
        if (mid <= rejectFrom && high < acceptFrom) return Verdict.Incorrect;
        return Verdict.Uncertain;
    }

    /// <summary>A short description of features for logs.</summary>
    public static string Describe(float[] f)
    {
        if (f == null) return "-";
        CultureInfo inv = CultureInfo.InvariantCulture;
        List<string> parts = new List<string>();
        for (int i = 0; i < FeatureCount; i++)
            parts.Add(FeatureNames[i] + " " + (float.IsNaN(f[i]) ? "-" : f[i].ToString("0.00", inv)));
        return string.Join(", ", parts.ToArray());
    }

    private static float Clamp(float v, float lo, float hi) { return v < lo ? lo : v > hi ? hi : v; }

    private static float[] WithNoise(float[] x, float db, int seed)
    {
        Random rng = new Random(seed);
        double amp = Math.Pow(10, db / 20) * Math.Sqrt(3);
        float[] y = new float[x.Length];
        for (int i = 0; i < x.Length; i++) y[i] = x[i] + (float)((rng.NextDouble() * 2 - 1) * amp);
        return y;
    }

    // ---- Trained models (PronunciationModelData.cs) ----------------------------------

    private static Dictionary<string, Model> table;

    /// <summary>The trained model for a word, or null when none has been trained.</summary>
    public static Model For(string word)
    {
        Load();
        Model m;
        return !string.IsNullOrEmpty(word) && table.TryGetValue(word.Trim(), out m) ? m : null;
    }

    /// <summary>Replaces a word's model (the builder evaluates with this); null removes it.</summary>
    public static void Override(string word, Model m)
    {
        Load();
        if (m == null) table.Remove(word);
        else table[word] = m;
    }

    /// <summary>Drops every loaded model (tests use this to see the game without the classifier).</summary>
    public static void ClearForTests() { Load(); table.Clear(); }

    /// <summary>Re-reads the generated models.</summary>
    public static void Reload() { table = null; Load(); }

    private static void Load()
    {
        if (table != null) return;
        Dictionary<string, Model> t = new Dictionary<string, Model>(StringComparer.OrdinalIgnoreCase);
        foreach (Row row in Rows)
        {
            Model m = new Model
            {
                word = row.word,
                bias = row.bias,
                acceptFrom = row.acceptFrom,
                rejectFrom = row.rejectFrom,
                trainedOn = row.trainedOn,
            };
            for (int i = 0; i < FeatureCount; i++)
            {
                m.use[i] = row.use[i] == '1';
                m.mean[i] = row.mean[i];
                m.scale[i] = row.scale[i];
                m.weight[i] = row.weight[i];
            }
            foreach (string f in row.taught) m.taughtRefs.Add(PronunciationTemplate.Decode(f));
            foreach (string f in row.other) m.otherRefs.Add(PronunciationTemplate.Decode(f));
            t[row.word] = m;
        }
        table = t;
    }

    private struct Row
    {
        public string word, use, trainedOn;
        public float[] mean, scale, weight;
        public float bias, acceptFrom, rejectFrom;
        public string[] taught, other;

        public Row(string word, string use, float[] mean, float[] scale, float[] weight, float bias,
                   float acceptFrom, float rejectFrom, string trainedOn, string[] taught, string[] other)
        {
            this.word = word; this.use = use; this.mean = mean; this.scale = scale; this.weight = weight; this.bias = bias;
            this.acceptFrom = acceptFrom; this.rejectFrom = rejectFrom; this.trainedOn = trainedOn;
            this.taught = taught; this.other = other;
        }
    }
}

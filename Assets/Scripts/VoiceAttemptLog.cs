using System;
using System.Globalization;
using System.IO;
using System.Text;
using UnityEngine;
using UnityEngine.SceneManagement;

/// <summary>
/// Writes one CSV row per voice attempt, so the word list can be tuned from
/// what children actually say instead of from guesses, and so the recognition
/// latency can be read off a real device instead of estimated.
///
/// WHY: WordVariants only buys accuracy if its entries are real. The entries
/// that ship are informed guesses; these rows are the measurement. Play a
/// scene, pull the file, and read the rawSpokenText column for rows marked
/// "mali" where the child in fact said the word correctly - each of those is a
/// line to add to WordVariants. The same rows are the accuracy numbers to cite
/// in the defense.
///
/// Static on purpose: no component to add, no scene to rebuild. VoiceCommand
/// calls straight into it, which matters because every scene in this project is
/// generated by a builder script.
///
/// THE LATENCY COLUMNS
///
/// Activity 10's monitoring plan says the voice round trip is to be read "from
/// the timestamps in salinlahi_voice_attempts.csv". It could not be: the
/// timestamp column is a wall clock stamp per row, which gives the gap BETWEEN
/// attempts, not the delay inside one. The five columns after verdict are that
/// missing measurement, filled in by VoiceCommand from the recognizer's own
/// callbacks. Every one of them is a real elapsed time on the device, and an
/// unmeasured one is written as an empty field rather than a zero.
///
///   listenToResultMs        the whole listening cycle: the recognizer said it
///                           was ready, and this is when the result arrived.
///                           Includes however long the child sat silent first,
///                           so it is not a reaction time.
///   speechToResultMs        from the recognizer noticing speech to the result.
///                           Still includes the time spent speaking the word,
///                           so treat it as an UPPER BOUND on the wait.
///   lastPartialToResultMs   from the last partial transcript to the result.
///                           Partials stop arriving when the talking stops, so
///                           this is the closest honest proxy for "the child
///                           finished speaking, and the game answered". This is
///                           the number to quote, and only when partialCount is
///                           above 0 - some devices send no partials at all.
///   partialCount            how many partial transcripts arrived. 0 means the
///                           column above is empty and speechToResultMs is the
///                           only figure available for that attempt.
///   verdictMs               from the result arriving to the verdict being
///                           decided. This is OUR code - canonicalisation and
///                           the variant match - and nothing else. Expect
///                           microseconds; Tools/perf_probe measures 5.64 us on
///                           a desktop.
///
/// The gap between lastPartialToResultMs and verdictMs is the point: if the
/// wait is long, it is the device's recognizer and its network call, not this
/// project's code, and the plan's 1.5 second threshold is about the first.
///
/// THE STRESS COLUMNS
///
/// For the words whose meaning depends on their stress (see AnswerJudge):
///
///   stressSource     raw_audio (the game's own recording), voice_levels (the
///                    recognizer's loudness readings) or empty (not checked).
///   stressVerdict    matches / wrong_stress / unmeasurable, as measured -
///                    even for a word whose stress is not enforced.
///   stressEnforced   1 if that verdict decided the answer.
///   stressMeasured   the player's score, and stressCutoff the line it was
///                    held against; Rachel's own is stressReference. These
///                    three are how the tolerance gets tuned: rows of a child
///                    saying tayô correctly that land on the wrong side of the
///                    cut-off mean it is too strict.
///
/// The verdict column gains "mali_diin" (right letters, wrong stress - scored
/// as wrong) and "hindi_malinaw" (stress could not be judged; asked again and
/// never scored). A file started before these columns existed keeps its old
/// header; delete it to get the new one.
///
/// WHERE THE FILE GOES
///
///   Editor:  ~/Library/Application Support/&lt;company&gt;/&lt;product&gt;/
///   Android: /sdcard/Android/data/&lt;package&gt;/files/
///
/// The exact path is logged once per run - look for "VoiceAttemptLog:" in the
/// Console or in `adb logcat`. To pull it off a device:
///
///   adb pull /sdcard/Android/data/&lt;package&gt;/files/salinlahi_voice_attempts.csv
///
/// Docs/perf/DeviceMeasurement.md has the whole procedure.
///
/// Kept deliberately LOCAL - never uploaded to Supabase. These rows are
/// children's speech, which is not something to put in a shared database for a
/// class project.
/// </summary>
public static class VoiceAttemptLog
{
    public const string FileName = "salinlahi_voice_attempts.csv";

    private const string Header =
        "timestamp,scene,targetWord,canonicalTarget,rawSpokenText,canonicalSpoken,verdict," +
        "listenToResultMs,speechToResultMs,lastPartialToResultMs,partialCount,verdictMs," +
        "stressSource,stressVerdict,stressEnforced,stressMeasured,stressCutoff,stressReference";

    /// <summary>Verdict column values. "nothing_heard" is not an answer and is never scored.</summary>
    public const string VerdictCorrect = "tama";
    public const string VerdictWrong = "mali";
    public const string VerdictNothingHeard = "nothing_heard";
    public const string VerdictWrongStress = "mali_diin";
    public const string VerdictUnclear = "hindi_malinaw";

    /// <summary>
    /// The elapsed times for one recognition attempt, measured by VoiceCommand
    /// from the recognizer's callbacks. See the latency columns described on
    /// this class. A negative value means "not measured on this attempt" and is
    /// written as an empty field, never as a zero - a zero would read as an
    /// instant answer, which would be a lie.
    /// </summary>
    public struct Latency
    {
        public double listenToResultMs;
        public double speechToResultMs;
        public double lastPartialToResultMs;
        public int partialCount;
        public double verdictMs;

        /// <summary>
        /// Nothing was measured. Used for the Editor keyboard fallback and any
        /// other simulated speech, where there is no recognizer to time.
        /// </summary>
        public static Latency None
        {
            get
            {
                Latency l;
                l.listenToResultMs = -1;
                l.speechToResultMs = -1;
                l.lastPartialToResultMs = -1;
                l.partialCount = -1;
                l.verdictMs = -1;
                return l;
            }
        }
    }

    private static bool pathReported;
    private static bool writeFailed;

    /// <summary>Full path of the CSV, for the log line and the editor tool.</summary>
    public static string FilePath
    {
        get { return Path.Combine(Application.persistentDataPath, FileName); }
    }

    /// <summary>
    /// Records one answered attempt. targetWord may be empty when no objective
    /// is live (a general command like "Talon"), in which case the row still
    /// shows what was heard.
    /// </summary>
    public static void Record(string targetWord, string spokenText, bool wasCorrect)
    {
        Record(targetWord, spokenText, wasCorrect, Latency.None);
    }

    /// <summary>
    /// Records one answered attempt together with how long it took. This is the
    /// overload VoiceCommand uses on a device; the one above is for simulated
    /// speech, which has no timings to report.
    /// </summary>
    public static void Record(string targetWord, string spokenText, bool wasCorrect, Latency latency)
    {
        Write(targetWord, spokenText, wasCorrect ? VerdictCorrect : VerdictWrong, latency, "");
    }

    /// <summary>Records one judged attempt, with its stress check if there was one.</summary>
    public static void Record(string targetWord, string spokenText, AnswerJudge.Result verdict, Latency latency)
    {
        string v;
        switch (verdict.outcome)
        {
            case AnswerJudge.Outcome.Correct: v = VerdictCorrect; break;
            case AnswerJudge.Outcome.WrongStress: v = VerdictWrongStress; break;
            case AnswerJudge.Outcome.Unclear: v = VerdictUnclear; break;
            default: v = VerdictWrong; break;
        }
        Write(targetWord, spokenText, v, latency, StressColumns(verdict));
    }

    private static string StressColumns(AnswerJudge.Result r)
    {
        if (r.pattern == null || r.source == AnswerJudge.StressSource.None) return "";
        string source = r.source == AnswerJudge.StressSource.RawAudio ? "raw_audio" : "voice_levels";
        string verdict = r.stress.verdict == StressAnalyzer.Verdict.Matches ? "matches"
                       : r.stress.verdict == StressAnalyzer.Verdict.WrongStress ? "wrong_stress" : "unmeasurable";
        return source + "," + verdict + "," + (r.stressEnforced ? "1" : "0") + "," +
               Number(r.stress.measured) + "," + Number(r.stress.threshold) + "," + Number(r.stress.reference);
    }

    private static string Number(float v)
    {
        return float.IsNaN(v) ? "" : v.ToString("0.000", CultureInfo.InvariantCulture);
    }

    /// <summary>
    /// Records that the player spoke but the recognizer could not make it out.
    /// Logged because that is an accuracy problem too - a word that is never
    /// transcribed needs a clearer prompt, not a new variant.
    /// </summary>
    public static void RecordNothingHeard(string targetWord)
    {
        RecordNothingHeard(targetWord, Latency.None);
    }

    /// <summary>
    /// Records a failed recognition with its timings. Worth keeping: the time
    /// spent before a failure is time the child waited too, and leaving these
    /// rows out would flatter the average.
    /// </summary>
    public static void RecordNothingHeard(string targetWord, Latency latency)
    {
        Write(targetWord, "", VerdictNothingHeard, latency, "");
    }

    private static void Write(string targetWord, string spokenText, string verdict, Latency latency, string stress)
    {
        // Logging must never be able to break a lesson, so every failure here
        // is swallowed after being reported once.
        if (writeFailed) return;

        try
        {
            string path = FilePath;
            bool needsHeader = !File.Exists(path);

            StringBuilder row = new StringBuilder();
            if (needsHeader) row.AppendLine(Header);

            row.Append(Escape(DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture))).Append(',')
               .Append(Escape(SceneManager.GetActiveScene().name)).Append(',')
               .Append(Escape(targetWord)).Append(',')
               .Append(Escape(PronunciationChecker.Canonicalize(targetWord))).Append(',')
               .Append(Escape(spokenText)).Append(',')
               .Append(Escape(PronunciationChecker.Canonicalize(spokenText))).Append(',')
               .Append(Escape(verdict)).Append(',')
               .Append(Millis(latency.listenToResultMs)).Append(',')
               .Append(Millis(latency.speechToResultMs)).Append(',')
               .Append(Millis(latency.lastPartialToResultMs)).Append(',')
               .Append(latency.partialCount < 0 ? "" : latency.partialCount.ToString(CultureInfo.InvariantCulture)).Append(',')
               .Append(Millis(latency.verdictMs)).Append(',')
               .Append(string.IsNullOrEmpty(stress) ? ",,,,," : stress);
            row.AppendLine();

            File.AppendAllText(path, row.ToString(), Encoding.UTF8);

            // Mirror to the Console so a playtest is readable in adb logcat
            // even without pulling the file. The wait is included because it is
            // the one number that cannot be recovered afterwards if the file is
            // lost, and because it makes a slow attempt obvious while the phone
            // is still in hand.
            Debug.Log(string.Format(
                "VoiceAttemptLog: [{0}] target=\"{1}\" heard=\"{2}\" wait={3} ms (partials={4}) verdict={5} ms",
                verdict, targetWord, spokenText,
                Millis(latency.lastPartialToResultMs >= 0 ? latency.lastPartialToResultMs : latency.speechToResultMs),
                latency.partialCount < 0 ? "-" : latency.partialCount.ToString(CultureInfo.InvariantCulture),
                Millis(latency.verdictMs)));

            if (!pathReported)
            {
                pathReported = true;
                Debug.Log("VoiceAttemptLog: writing attempts to " + path);
            }
        }
        catch (Exception e)
        {
            writeFailed = true;
            Debug.LogWarning("VoiceAttemptLog: couldn't write the attempt log, carrying on without it: " + e.Message);
        }
    }

    /// <summary>
    /// One millisecond figure for the CSV. Negative means unmeasured, which is
    /// an empty field: a zero there would read as an instant answer. Three
    /// decimals so verdictMs, which is microseconds, does not round to 0.
    /// </summary>
    private static string Millis(double ms)
    {
        if (ms < 0) return "";
        return ms.ToString("0.###", CultureInfo.InvariantCulture);
    }

    /// <summary>Standard CSV quoting, so a recognized phrase with a comma can't shift the columns.</summary>
    private static string Escape(string field)
    {
        if (string.IsNullOrEmpty(field)) return "";
        if (field.IndexOfAny(new[] { ',', '"', '\n', '\r' }) < 0) return field;
        return "\"" + field.Replace("\"", "\"\"") + "\"";
    }
}

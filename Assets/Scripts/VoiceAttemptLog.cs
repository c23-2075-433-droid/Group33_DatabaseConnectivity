using System;
using System.Globalization;
using System.IO;
using System.Text;
using UnityEngine;
using UnityEngine.SceneManagement;

/// <summary>
/// Writes one CSV row per voice attempt, so the word list can be tuned from
/// what children actually say instead of from guesses.
///
/// WHY: WordVariants only buys accuracy if its entries are real. The entries
/// that ship are informed guesses; these rows are the measurement. Play a
/// scene, pull the file, and read the rawSpokenText column for rows marked
/// "mali" where the child in fact said the word correctly - each of those is a
/// line to add to WordVariants. The same rows are the accuracy numbers to cite
/// in the defense.
///
/// Static on purpose: no component to add, no scene to rebuild. VoiceCommand
/// calls straight into it, which matters because every scene in this project is
/// generated by a builder script.
///
/// WHERE THE FILE GOES
///
///   Editor:  ~/Library/Application Support/<company>/<product>/
///   Android: /sdcard/Android/data/&lt;package&gt;/files/
///
/// The exact path is logged once per run - look for "VoiceAttemptLog:" in the
/// Console or in `adb logcat`. To pull it off a device:
///
///   adb pull /sdcard/Android/data/&lt;package&gt;/files/salinlahi_voice_attempts.csv
///
/// Kept deliberately LOCAL - never uploaded to Supabase. These rows are
/// children's speech, which is not something to put in a shared database for a
/// class project.
/// </summary>
public static class VoiceAttemptLog
{
    public const string FileName = "salinlahi_voice_attempts.csv";

    private const string Header =
        "timestamp,scene,targetWord,canonicalTarget,rawSpokenText,canonicalSpoken,verdict";

    /// <summary>Verdict column values. "nothing_heard" is not an answer and is never scored.</summary>
    public const string VerdictCorrect = "tama";
    public const string VerdictWrong = "mali";
    public const string VerdictNothingHeard = "nothing_heard";

    private static bool pathReported;
    private static bool writeFailed;

    /// <summary>Full path of the CSV, for the log line and the editor tool.</summary>
    public static string FilePath
    {
        get { return Path.Combine(Application.persistentDataPath, FileName); }
    }

    /// <summary>
    /// Records one answered attempt. targetWord may be empty when no objective
    /// is live (a general command like "Talon"), in which case the row still
    /// shows what was heard.
    /// </summary>
    public static void Record(string targetWord, string spokenText, bool wasCorrect)
    {
        Write(targetWord, spokenText, wasCorrect ? VerdictCorrect : VerdictWrong);
    }

    /// <summary>
    /// Records that the player spoke but the recognizer could not make it out.
    /// Logged because that is an accuracy problem too - a word that is never
    /// transcribed needs a clearer prompt, not a new variant.
    /// </summary>
    public static void RecordNothingHeard(string targetWord)
    {
        Write(targetWord, "", VerdictNothingHeard);
    }

    private static void Write(string targetWord, string spokenText, string verdict)
    {
        // Logging must never be able to break a lesson, so every failure here
        // is swallowed after being reported once.
        if (writeFailed) return;

        try
        {
            string path = FilePath;
            bool needsHeader = !File.Exists(path);

            StringBuilder row = new StringBuilder();
            if (needsHeader) row.AppendLine(Header);

            row.Append(Escape(DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture))).Append(',')
               .Append(Escape(SceneManager.GetActiveScene().name)).Append(',')
               .Append(Escape(targetWord)).Append(',')
               .Append(Escape(PronunciationChecker.Canonicalize(targetWord))).Append(',')
               .Append(Escape(spokenText)).Append(',')
               .Append(Escape(PronunciationChecker.Canonicalize(spokenText))).Append(',')
               .Append(Escape(verdict));
            row.AppendLine();

            File.AppendAllText(path, row.ToString(), Encoding.UTF8);

            // Mirror to the Console so a playtest is readable in adb logcat
            // even without pulling the file.
            Debug.Log(string.Format("VoiceAttemptLog: [{0}] target=\"{1}\" heard=\"{2}\"",
                verdict, targetWord, spokenText));

            if (!pathReported)
            {
                pathReported = true;
                Debug.Log("VoiceAttemptLog: writing attempts to " + path);
            }
        }
        catch (Exception e)
        {
            writeFailed = true;
            Debug.LogWarning("VoiceAttemptLog: couldn't write the attempt log, carrying on without it: " + e.Message);
        }
    }

    /// <summary>Standard CSV quoting, so a recognized phrase with a comma can't shift the columns.</summary>
    private static string Escape(string field)
    {
        if (string.IsNullOrEmpty(field)) return "";
        if (field.IndexOfAny(new[] { ',', '"', '\n', '\r' }) < 0) return field;
        return "\"" + field.Replace("\"", "\"\"") + "\"";
    }
}

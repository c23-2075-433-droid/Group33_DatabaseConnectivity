using System.Collections;
using UnityEngine;
using UnityEngine.SceneManagement;
using UnityEngine.UI;

/// <summary>
/// The in-game interface: the back button, Teacher Rachel's plaque, the menu
/// button, the place and listening planks, and the signpost carrying the word
/// to say and what it means.
///
/// Nothing here decides anything about the game. Every value on screen is read
/// from a system that already exists - SceneObjectiveController for the word,
/// VoiceCommand for the microphone, VoiceNarrator for Rachel, JourneyMap for
/// where the player is - and the only things it changes are the ones a player
/// asked it to: the volume, the pause while the settings are open, and leaving
/// for the level select.
///
/// It is built at RUN TIME and nothing in any scene refers to it. That is not
/// a shortcut: the fifteen chapter scenes are generated by the Build*Scene*
/// menu items and anything added to a saved scene is destroyed the next time
/// one is run. Chapter 1 Level 1 has no builder at all and is maintained by
/// hand. A HUD added to either would have to be added fifteen times and would
/// not survive. Built from nothing on every scene load, it survives everything
/// and the builders never have to know it exists. Same reasoning, and the same
/// bootstrap, as VoicePromptDirector - see Docs/VoicePromptingDesign.md 6.3.
/// </summary>
public class GameplayHUD : MonoBehaviour, ICaptionPresenter
{
    [Header("Where this goes back to")]
    public string levelSelectSceneName = "LevelSelect";

    [Header("Fades")]
    public float panelFadeSeconds = 0.15f;

    [Header("Listening panel")]
    [Tooltip("Tuning for the state shown under the microphone. See VoiceStatusMachine for what each one prevents.")]
    public float feedbackHold = 1.2f;
    public float listeningGrace = 1.2f;
    public float minDwell = 0.5f;

    [Header("Microphone")]
    [Tooltip("Move and re-skin the microphone the scene already has, so it matches the rest of the HUD. " +
             "Off, the scene's own mic is left exactly where its builder put it.")]
    public bool restyleMicrophone = true;

    // What each state says. Fixed strings, built once: assigning Text.text
    // re-lays the mesh out even when the value has not changed, so the label
    // is only written when the state actually moves.
    private static readonly string[] StateLabels =
    {
        "",                 // Idle
        "SPEAK NOW",
        "LISTENING...",
        "PROCESSING...",
        "TEACHER RACHEL",
        "CORRECT!",
        "TRY AGAIN",
        "MIC IS OFF",
    };

    private static readonly Color StateNormal  = new Color(0.99f, 0.95f, 0.86f);
    private static readonly Color StateCorrect = new Color(0.72f, 0.95f, 0.62f);
    private static readonly Color StateRetry   = new Color(1f, 0.85f, 0.52f);
    private static readonly Color StateBlocked = new Color(1f, 0.62f, 0.55f);

    private GameplayHUDLayout.Parts ui;
    private UITheme theme;
    private VoiceStatusMachine status;

    private SceneObjectiveController controller;
    private VoiceCommand voice;
    private VoiceNarrator narrator;          // cached: never ask for Instance during teardown
    private VoiceInteractionUI voiceUI;

    private SceneObjectiveController.SceneObjective shownObjective;
    private Coroutine narrationFade;
    private Coroutine wordFade;
    private Rect lastSafeArea;
    private bool settingsOpen;
    private bool chromeHidden;

    // ------------------------------------------------------------------

    void Awake()
    {
        controller = FindFirstObjectByType<SceneObjectiveController>();
        if (controller == null)
        {
            enabled = false;
            return;
        }

        voice = controller.voiceCommand != null
            ? controller.voiceCommand
            : FindFirstObjectByType<VoiceCommand>();
        voiceUI = FindFirstObjectByType<VoiceInteractionUI>();
        narrator = VoiceNarrator.Instance;

        theme = UITheme.Load();
        BuildCanvas();

        status = new VoiceStatusMachine
        {
            feedbackHold = feedbackHold,
            listeningGrace = listeningGrace,
            minDwell = minDwell,
        };
        status.OnChanged += ShowState;

        Subscribe();

        VolumeSettings.Apply();
        ShowPlace();
        ShowState(status.Current);
        if (restyleMicrophone) RestyleMicrophone();

        // Rachel may already be mid-line: VoicePromptDirector queues the scene
        // intro in its own Awake, and both bootstraps run in the same pass, so
        // which of us goes first is not ours to decide. Taking over the caption
        // surface replays whatever is on screen, so the order cannot matter.
        if (narrator != null) narrator.CaptionPresenter = this;
    }

    void OnDestroy()
    {
        Unsubscribe();
        if (status != null) status.OnChanged -= ShowState;

        // The cached reference, never VoiceNarrator.Instance - its getter
        // CREATES a narrator if there is none, which during a scene change
        // would resurrect the object we are being destroyed alongside.
        if (narrator != null && ReferenceEquals(narrator.CaptionPresenter, this))
            narrator.CaptionPresenter = null;
    }

    private void Subscribe()
    {
        controller.OnObjectiveShown += HandleObjectiveShown;
        controller.OnObjectiveCompleted += HandleObjectiveCompleted;
        controller.onAllObjectivesComplete.AddListener(HandleSceneComplete);

        if (voice != null)
        {
            voice.OnAnswerChecked += HandleAnswerChecked;
            voice.OnSpeechBegan += HandleSpeechBegan;
            voice.OnMicrophoneUnavailable += HandleMicrophoneUnavailable;
        }

        ui.backButton.onClick.AddListener(OnBackPressed);
        ui.menuButton.onClick.AddListener(OnMenuPressed);
    }

    private void Unsubscribe()
    {
        if (controller != null)
        {
            controller.OnObjectiveShown -= HandleObjectiveShown;
            controller.OnObjectiveCompleted -= HandleObjectiveCompleted;
            controller.onAllObjectivesComplete.RemoveListener(HandleSceneComplete);
        }
        if (voice != null)
        {
            voice.OnAnswerChecked -= HandleAnswerChecked;
            voice.OnSpeechBegan -= HandleSpeechBegan;
            voice.OnMicrophoneUnavailable -= HandleMicrophoneUnavailable;
        }
        if (ui != null)
        {
            if (ui.backButton != null) ui.backButton.onClick.RemoveListener(OnBackPressed);
            if (ui.menuButton != null) ui.menuButton.onClick.RemoveListener(OnMenuPressed);
        }
    }

    private void BuildCanvas()
    {
        Canvas canvas = gameObject.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        // Above the world-space word badges (10) and the mic buttons (0), below
        // the scene's result panel (50) and the fader (999).
        canvas.sortingOrder = 40;

        CanvasScaler scaler = gameObject.AddComponent<CanvasScaler>();
        scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
        scaler.referenceResolution = new Vector2(1920, 1080);
        scaler.screenMatchMode = CanvasScaler.ScreenMatchMode.Expand;
        gameObject.AddComponent<GraphicRaycaster>();

        if (FindFirstObjectByType<UnityEngine.EventSystems.EventSystem>() == null)
        {
            GameObject es = new GameObject("EventSystem");
            es.AddComponent<UnityEngine.EventSystems.EventSystem>();
            es.AddComponent<UnityEngine.EventSystems.StandaloneInputModule>();
        }

        ui = GameplayHUDLayout.Build(transform, theme, UITheme.Display(), UITheme.Body());
        ApplySafeArea();
    }

    // ------------------------------------------------------------------
    // Rachel's plaque - the caption surface VoiceNarrator speaks through
    // ------------------------------------------------------------------

    /// <summary>
    /// Shows one of Rachel's lines. VoiceNarrator still decides WHAT is said
    /// and WHEN; all that moves here is where it is drawn, so there is one
    /// subtitle system rather than two that can disagree.
    /// </summary>
    public void ShowCaption(string text)
    {
        if (ui == null || ui.narrationPanel == null) return;

        bool show = !string.IsNullOrEmpty(text);
        if (show) ui.narrationText.text = text;

        if (narrationFade != null) StopCoroutine(narrationFade);
        narrationFade = StartCoroutine(Fade(ui.narrationPanel, ui.narrationFade, show));
    }

    // ------------------------------------------------------------------
    // the word being asked for
    // ------------------------------------------------------------------

    private void HandleObjectiveShown(SceneObjectiveController.SceneObjective objective)
    {
        shownObjective = objective;
        status.NoteObjectiveChanged();

        if (objective == null)
        {
            HideWord();
            return;
        }

        // The spelling on the signpost is the word's own, uppercased only for
        // reading - the same way the badge over the object shows it.
        ui.wordText.text = objective.word != null ? objective.word.Trim().ToUpperInvariant() : "";

        string gloss = NarratorScript.GlossFor(objective.word);
        ui.glossText.text = gloss;
        // No meaning recorded for this word: leave the line out rather than
        // leave a gap under the word.
        ui.glossText.gameObject.SetActive(!string.IsNullOrEmpty(gloss));

        ShowWord(true);
    }

    private void HandleObjectiveCompleted(string word)
    {
        shownObjective = null;
        status.NoteCorrect();
        HideWord();
    }

    private void HandleSceneComplete()
    {
        shownObjective = null;
        HideWord();

        // The scene's summary is about to open over the top. The result panel
        // sorts above this canvas but the level-complete sheet does not, so the
        // chrome gets out of the way rather than drawing over either.
        //
        // Rachel's plaque stays: the scene's outro line is spoken from exactly
        // this moment, and hiding the whole HUD would caption it to nobody.
        ShowChrome(false);
    }

    /// <summary>Everything except Rachel's plaque, which has to outlive the scene's end.</summary>
    private void ShowChrome(bool show)
    {
        if (ui == null) return;
        if (ui.backButton != null) ui.backButton.gameObject.SetActive(show);
        if (ui.menuButton != null) ui.menuButton.gameObject.SetActive(show);
        if (ui.placePlank != null) ui.placePlank.SetActive(show);
        if (ui.statePlank != null) ui.statePlank.SetActive(show);
        chromeHidden = !show;
    }

    private void HandleAnswerChecked(string spokenText, bool wasCorrect)
    {
        // The correct case is handled by HandleObjectiveCompleted, which the
        // controller raises BEFORE it moves on - so "CORRECT!" is always about
        // the word that was just answered, never the next one.
        if (!wasCorrect) status.NoteTryAgain();
    }

    private void HandleSpeechBegan()
    {
        status.NoteSpeechBegan();
    }

    private void HandleMicrophoneUnavailable()
    {
        status.NoteMicBlocked();
    }

    private void ShowWord(bool show)
    {
        if (wordFade != null) StopCoroutine(wordFade);
        wordFade = StartCoroutine(Fade(ui.wordSign, ui.wordFade, show, WordAlpha()));
    }

    /// <summary>
    /// How bright the signpost is. It follows the badge over the object: faint
    /// while Rachel is still introducing the word - seen, but not yet yours to
    /// say - and full strength the moment the recognizer is actually listening
    /// for it. Reading the controller's own dimmedPromptAlpha rather than
    /// keeping a second number means the two can never drift apart.
    /// </summary>
    private float WordAlpha()
    {
        if (controller == null) return 1f;
        return controller.CurrentObjective != null ? 1f : controller.dimmedPromptAlpha;
    }

    private void HideWord()
    {
        ShowWord(false);
    }

    // ------------------------------------------------------------------
    // the two planks
    // ------------------------------------------------------------------

    /// <summary>
    /// "BAHAY: LEVEL 1", from the journey itself rather than anything typed in
    /// here, so a scene always names its own place.
    /// </summary>
    private void ShowPlace()
    {
        ui.placeText.text = JourneyMap.PlaceLabel(SceneManager.GetActiveScene().name);
    }

    private void ShowState(VoiceStatusMachine.State state)
    {
        int i = (int)state;
        ui.stateText.text = i >= 0 && i < StateLabels.Length ? StateLabels[i] : "";
        ui.stateText.color = StateColour(state);

        // The plank is the label: with nothing to say it goes away rather than
        // sitting empty under the microphone. Once the scene is over it stays
        // away, whatever the recognizer does next.
        bool visible = !chromeHidden && !string.IsNullOrEmpty(ui.stateText.text);
        if (ui.statePlank.activeSelf != visible)
            ui.statePlank.SetActive(visible);

        if (voiceUI != null) voiceUI.SetVisual(MicVisualFor(state));
    }

    private static Color StateColour(VoiceStatusMachine.State state)
    {
        switch (state)
        {
            case VoiceStatusMachine.State.Correct:    return StateCorrect;
            case VoiceStatusMachine.State.TryAgain:   return StateRetry;
            case VoiceStatusMachine.State.MicBlocked: return StateBlocked;
            default:                                  return StateNormal;
        }
    }

    private static VoiceInteractionUI.MicVisual MicVisualFor(VoiceStatusMachine.State state)
    {
        switch (state)
        {
            case VoiceStatusMachine.State.Listening:  return VoiceInteractionUI.MicVisual.Listening;
            case VoiceStatusMachine.State.Processing: return VoiceInteractionUI.MicVisual.Processing;
            case VoiceStatusMachine.State.MicBlocked: return VoiceInteractionUI.MicVisual.Blocked;
            default:                                  return VoiceInteractionUI.MicVisual.Idle;
        }
    }

    void Update()
    {
        if (ui == null) return;

        // A word is the player's only once the controller has handed it to the
        // recognizer. While Rachel is still introducing it the badge is dim,
        // the word is not being matched, and the panel should not claim it is
        // listening - CurrentObjective is null through exactly that window.
        bool objectiveLive = controller != null && controller.CurrentObjective != null;
        bool speaking = narrator != null && narrator.IsSpeaking;
        bool listening = voice != null && voice.IsListening;

        if (settingsOpen || (controller != null && controller.IsPaused))
        {
            objectiveLive = false;
        }

        status.Tick(Time.deltaTime, objectiveLive, speaking, listening);

        // Keeps the signpost in step with the badge as the word goes live.
        // Skipped while a fade is running - that coroutine owns the alpha
        // until it finishes, and it was started with the right target.
        if (wordFade == null && shownObjective != null && ui.wordSign.activeSelf)
        {
            ui.wordFade.alpha = WordAlpha();
        }

        if (lastSafeArea != Screen.safeArea) ApplySafeArea();
    }

    // ------------------------------------------------------------------
    // buttons
    // ------------------------------------------------------------------

    private void OnBackPressed()
    {
        // Stop her mid-sentence: she should not keep talking over the fade out.
        if (narrator != null) narrator.StopSpeaking();

        SceneFader fader = FindFirstObjectByType<SceneFader>();
        if (fader != null) fader.FadeOutAndLoad(levelSelectSceneName);
        else SceneManager.LoadScene(levelSelectSceneName);
    }

    private void OnMenuPressed()
    {
        GameplayHUDLayout.BuildSettings(ui, ui.safeArea, theme, UITheme.Display());

        if (ui.masterSlider != null)
        {
            ui.masterSlider.SetValueWithoutNotify(VolumeSettings.Master);
            ui.masterSlider.onValueChanged.RemoveListener(OnMasterChanged);
            ui.masterSlider.onValueChanged.AddListener(OnMasterChanged);
        }
        if (ui.narrationSlider != null)
        {
            ui.narrationSlider.SetValueWithoutNotify(VolumeSettings.Narration);
            ui.narrationSlider.onValueChanged.RemoveListener(OnNarrationChanged);
            ui.narrationSlider.onValueChanged.AddListener(OnNarrationChanged);
        }
        if (ui.settingsClose != null)
        {
            ui.settingsClose.onClick.RemoveListener(CloseSettings);
            ui.settingsClose.onClick.AddListener(CloseSettings);
        }

        settingsOpen = true;
        ui.settingsPanel.SetActive(true);

        // Hold the sequence the same way a door transition does, so the child
        // is not still being asked for a word - and the recognizer not still
        // listening to the room - while the settings are open.
        if (controller != null) controller.SetPaused(true);
        if (narrator != null) narrator.StopSpeaking();
    }

    private void CloseSettings()
    {
        settingsOpen = false;
        if (ui.settingsPanel != null) ui.settingsPanel.SetActive(false);
        if (controller != null) controller.SetPaused(false);
    }

    private void OnMasterChanged(float value)
    {
        if (VolumeSettings.Muted) VolumeSettings.Muted = false;
        VolumeSettings.Master = value;
    }

    private void OnNarrationChanged(float value)
    {
        VolumeSettings.Narration = value;
    }

    // ------------------------------------------------------------------
    // the scene's own microphone, adopted
    // ------------------------------------------------------------------

    /// <summary>
    /// Moves and re-skins the microphone the scene builder already placed,
    /// rather than drawing a second one. VoiceInteractionUI keeps driving it:
    /// only its sprite and its rectangle change, at run time, so no scene file
    /// is touched and a rebuilt scene comes back with the same result.
    /// </summary>
    private void RestyleMicrophone()
    {
        if (voiceUI == null) return;

        if (voiceUI.micIcon != null)
        {
            if (theme != null && theme.micIcon != null) voiceUI.micIcon.sprite = theme.micIcon;
            voiceUI.micIcon.preserveAspect = true;
            RectTransform rect = voiceUI.micIcon.rectTransform;
            rect.anchoredPosition = GameplayHUDLayout.MicPosition;
            rect.sizeDelta = GameplayHUDLayout.MicSize;
        }

        // The replay button is not in the design's sketch, but it is how a
        // child who has forgotten the word hears it again without being
        // scored for asking - so it stays, beside the microphone.
        if (voiceUI.replayButton != null)
        {
            RectTransform rect = voiceUI.replayButton.GetComponent<RectTransform>();
            rect.anchoredPosition = GameplayHUDLayout.ReplayPosition;
            rect.sizeDelta = GameplayHUDLayout.ReplaySize;
        }
    }

    // ------------------------------------------------------------------
    // fades and the safe area
    // ------------------------------------------------------------------

    private IEnumerator Fade(GameObject target, CanvasGroup group, bool show, float shownAlpha = 1f)
    {
        if (show && !target.activeSelf) target.SetActive(true);

        float from = group.alpha;
        float to = show ? shownAlpha : 0f;
        for (float t = 0f; t < panelFadeSeconds; t += Time.deltaTime)
        {
            group.alpha = Mathf.Lerp(from, to, t / panelFadeSeconds);
            yield return null;
        }
        group.alpha = to;

        if (!show) target.SetActive(false);
        if (target == ui.narrationPanel) narrationFade = null;
        else wordFade = null;
    }

    /// <summary>
    /// Pulls the whole interface in from a notch or a gesture bar. Recomputed
    /// only when the area actually changes - on a rotation, or the first frame
    /// - rather than every frame.
    /// </summary>
    private void ApplySafeArea()
    {
        lastSafeArea = Screen.safeArea;
        if (Screen.width <= 0 || Screen.height <= 0) return;

        Vector2 min = lastSafeArea.position;
        Vector2 max = lastSafeArea.position + lastSafeArea.size;
        min.x /= Screen.width;
        min.y /= Screen.height;
        max.x /= Screen.width;
        max.y /= Screen.height;

        ui.safeArea.anchorMin = min;
        ui.safeArea.anchorMax = max;
        ui.safeArea.offsetMin = Vector2.zero;
        ui.safeArea.offsetMax = Vector2.zero;
    }
}

/// <summary>
/// Puts a GameplayHUD in every scene that asks the player for words, without
/// any scene storing a reference to one.
///
/// A straight copy of VoicePromptBootstrap, for the same reason: the chapter
/// scenes are generated, so a HUD added to a saved scene would be destroyed
/// the next time someone ran its builder. Nothing created at run time can be.
/// </summary>
public static class GameplayHUDBootstrap
{
    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
    private static void Install()
    {
        SceneManager.sceneLoaded -= OnSceneLoaded;
        SceneManager.sceneLoaded += OnSceneLoaded;
        Attach();
    }

    private static void OnSceneLoaded(Scene scene, LoadSceneMode mode)
    {
        Attach();
    }

    private static void Attach()
    {
        // Only where words are asked for: the main menu and the journey map
        // have their own interfaces and no SceneObjectiveController.
        if (Object.FindFirstObjectByType<SceneObjectiveController>() == null) return;
        if (Object.FindFirstObjectByType<GameplayHUD>() != null) return;

        GameObject go = new GameObject("GameplayHUD");
        go.AddComponent<GameplayHUD>();
    }
}

using UnityEngine;

/// <summary>
/// The fonts and sprites the in-game HUD is drawn from, in one asset a BUILD
/// can load.
///
/// This exists because the HUD is created at run time. Everything else in this
/// project that draws UI is an Editor script, so it reaches for
/// UIFont.Get() and AssetDatabase.LoadAssetAtPath - and neither of those
/// exists in an Android build. A ScriptableObject in Resources is the way a
/// runtime script gets hold of an asset by name, and NarratorVoiceBank already
/// solves exactly this problem for the voice-over clips, so this follows its
/// shape: generated by a menu item, never filled in by hand.
///
/// Generate it with Tools > SALINLAHI > Refresh UI Theme. The game still runs
/// without it - every field has a fallback - it just looks plain.
/// </summary>
[CreateAssetMenu(fileName = "UITheme", menuName = "SALINLAHI/UI Theme")]
public class UITheme : ScriptableObject
{
    /// <summary>Where Resources.Load looks for it. Must stay in a Resources folder.</summary>
    public const string ResourcePath = "UITheme";

    [Header("Fonts")]
    [Tooltip("Headings, vocabulary words, buttons - the chunky lettering painted into the art.")]
    public Font displayFont;

    [Tooltip("Subtitles and anything long enough to read a sentence of.")]
    public Font bodyFont;

    [Header("Panels")]
    [Tooltip("ui_narration_panel - the branch ring and plaque Rachel speaks from.")]
    public Sprite narrationPanel;

    [Tooltip("ui_word_signpost - the signpost carrying the word to say and its meaning.")]
    public Sprite wordSignpost;

    [Tooltip("ui_status_plank - used twice: the place/level label and the listening state.")]
    public Sprite statusPlank;

    [Tooltip("ui_settings_panel - the settings board. Its four rows, their icons and " +
             "their labels are painted into the art, so only the controls are built on top.")]
    public Sprite settingsPanel;

    [Header("Buttons")]
    public Sprite backButton;       // btn_back
    public Sprite menuButton;       // btn_menu_round
    public Sprite okayButton;       // btn_okay
    public Sprite settingsClose;    // btn_settings_close

    [Header("Toggles")]
    [Tooltip("ui_settings_toggle_on / _off - the two halves of a two-state control. " +
             "The ON and OFF lettering is part of the art, so the pair is swapped whole.")]
    public Sprite toggleOn;
    public Sprite toggleOff;

    [Header("Sliders")]
    [Tooltip("The track is a fixed width, so it stretches whole. The fill is NOT: it is " +
             "9-sliced, because it is the one piece whose width runs from nothing to full " +
             "and a stretched cap collapses into a sliver at the low end.")]
    public Sprite sliderTrack;
    public Sprite sliderFill;
    public Sprite sliderKnob;

    // The slider art's own proportions, measured off the Canva export by
    // Tools/cut_settings_ui.py. Fractions of the whole widget box, which is as
    // tall as the KNOB rather than as tall as the bar - the disc deliberately
    // overhangs the capsule top and bottom.
    //
    // They live here, beside the ring constants, because BOTH settings screens
    // build this same control - the menu popup in an Editor script and the HUD
    // panel at run time - and a copy in each is a copy that drifts.
    public const float BarCapsuleFraction = 0.764f;   // grey capsule, 97 of 127
    public const float BarOrangeFraction = 0.213f;    // orange fill, 27 of 127
    public const float BarKnobFraction = 0.984f;      // knob disc, 125 of 127
    public const float BarGrooveInset = 0.0311f;      // 35 of the track's 1126 px:
                                                      // 25 of grey rim plus 10 of groove

    /// <summary>
    /// The fill sprite's own height, in its own pixels. Unity draws a 9-slice
    /// border at native sprite pixels, so a bar rendered shorter than the sprite
    /// needs Image.pixelsPerUnitMultiplier set to this over the rendered height -
    /// otherwise the caps come out several times too big.
    /// </summary>
    public const float BarFillSourceHeight = 27f;

    /// <summary>
    /// The bar is drawn thin because that is the design, but a thin bar is a
    /// cruel tap target for a five-year-old - about 14 dp at this panel size,
    /// against Android's 48 dp guideline. Both screens put an invisible pad
    /// this tall over the row, which catches the misses without changing a
    /// pixel of the art.
    /// </summary>
    public const float BarMinTouchHeight = 110f;

    [Header("Microphone")]
    [Tooltip("mic_icon_wood - swapped onto the mic the scene already has, so the HUD matches without any scene being rebuilt.")]
    public Sprite micIcon;

    [Header("Characters")]
    [Tooltip("Teacher Rachel's head and shoulders, shown inside the branch ring. " +
             "Optional: with none, the ring frames the room behind it and the panel still reads.")]
    public Sprite rachelPortrait;

    [Tooltip("Her mouth slightly open. Optional: without the three talking frames she simply does not move while she speaks.")]
    public Sprite rachelTalk1;

    [Tooltip("Her mouth moderately open.")]
    public Sprite rachelTalk2;

    [Tooltip("Her mouth wide open.")]
    public Sprite rachelTalk3;

    [Tooltip("Her eyes gently closed. Optional: without it she never blinks between lines.")]
    public Sprite rachelBlink;

    // Where Rachel's face goes inside narrationPanel, as fractions of that
    // sprite. Measured off the art by Tools/cut_hud_assets.py, which prints
    // these three numbers every time it runs - re-cut a redrawn plaque and
    // paste its numbers here rather than nudging the portrait by eye.
    public const float RingCentreX = 0.1319f;
    public const float RingCentreY = 0.4744f;
    public const float RingDiameter = 0.1616f;

    // ------------------------------------------------------------------

    private static UITheme cached;
    private static bool looked;

    /// <summary>
    /// The theme asset, or null if it has not been generated yet. Looked up
    /// once: Resources.Load is cheap but this is asked for while building the
    /// HUD, and a null result should not re-search every time.
    /// </summary>
    public static UITheme Load()
    {
        if (looked) return cached;
        looked = true;
        cached = Resources.Load<UITheme>(ResourcePath);
        if (cached == null)
        {
            Debug.LogWarning("[SALINLAHI] No UITheme asset found. The HUD will draw with plain " +
                             "panels and the built-in font. Run Tools > SALINLAHI > Refresh UI Theme.");
        }
        return cached;
    }

    /// <summary>Drops the cache, so a regenerated asset is picked up without a domain reload.</summary>
    public static void Invalidate()
    {
        cached = null;
        looked = false;
    }

    void OnValidate()
    {
        Invalidate();
    }

    /// <summary>
    /// The heading font, falling back through the body font to Unity's
    /// built-in one. Unity renamed that between versions, so both names are
    /// tried rather than guessed at - the same dance VoiceNarrator does.
    /// </summary>
    public static Font Display()
    {
        UITheme theme = Load();
        if (theme != null && theme.displayFont != null) return theme.displayFont;
        return Body();
    }

    /// <summary>The reading font, falling back to Unity's built-in one.</summary>
    public static Font Body()
    {
        UITheme theme = Load();
        if (theme != null && theme.bodyFont != null) return theme.bodyFont;
        if (theme != null && theme.displayFont != null) return theme.displayFont;
        return BuiltinFont();
    }

    private static Font builtin;

    private static Font BuiltinFont()
    {
        if (builtin != null) return builtin;

        foreach (string name in new[] { "LegacyRuntime.ttf", "Arial.ttf" })
        {
            try
            {
                builtin = Resources.GetBuiltinResource<Font>(name);
                if (builtin != null) return builtin;
            }
            catch (System.Exception)
            {
                // Not in this Unity version - try the next one.
            }
        }
        return null;
    }
}
